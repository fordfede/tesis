def guardar_json(datos: Any, ruta: str) -> None:
    """
    Guarda una estructura como JSON en disco.

    Args:
        datos: objeto serializable a JSON.
        ruta: path de destino del archivo.
    """
    os.makedirs(os.path.dirname(ruta), exist_ok=True)
    with open(ruta, "w", encoding="utf-8") as f:
        json.dump(datos, f, ensure_ascii=False, indent=2)
    if DEBUG:
        print(f"[DEBUG] guardado: {ruta}")

def xrpl_extraer_bigquery(cliente, ledger_inicio: int) -> pd.DataFrame:
    """
    Extrae txs XRPL con memo desde BigQuery (YTD 2026).

    Args:
        cliente: bigquery.Client autenticado.
        ledger_inicio: LedgerIndex de arranque (corte YTD).

    Returns:
        DataFrame con transacciones exitosas y memo no vacío.
    """
    consulta = f"""
    SELECT
        `hash` AS tx_id,
        Account AS emisor,
        Destination AS receptor,
        AmountXRP AS amount,
        Fee AS fee,
        LedgerIndex AS ledger_index,
        memo.Memo.MemoData AS memo_raw
    FROM `xrpledgerdata.fullhistory.transactions`,
        UNNEST(Memos) AS memo
    WHERE LedgerIndex >= {ledger_inicio}
        AND TransactionResult = "tesSUCCESS"
        AND memo.Memo.MemoData IS NOT NULL
    """
    df = cliente.query(consulta).to_dataframe()
    if DEBUG:
        print(f"[DEBUG] XRPL BigQuery: {len(df)} txs con memo")
    return df

