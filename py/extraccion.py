def stellar_extraer(inicio: str,
                    max_paginas: int) -> list[dict]:
    """
    Pagina Horizon y recupera txs con memo hasta 'inicio'.

    Args:
        inicio: fecha mínima (ISO) de created_at a incluir.
        max_paginas: tope de páginas a recorrer.

    Returns:
        Lista de transacciones Stellar con memo no vacío.
    """
    url = (f"{STELLAR_HORIZON}/transactions"
           f"?order=desc&limit={PAGINA_STELLAR}"
           f"&include_failed=false")
    txs_memo: list[dict] = []
    with httpx.Client(timeout=TIMEOUT) as cliente:
        for pagina in range(max_paginas):
            try:
                r = cliente.get(url)
                r.raise_for_status()
                datos = r.json()
            except (httpx.HTTPError, ValueError) as e:
                if DEBUG:
                    print(f"[DEBUG] error Stellar: {e}")
                break
            registros = datos.get(
                "_embedded", {}).get("records", [])
            if not registros:
                break
            for tx in registros:
                if (not FILTRO_MEMO
                        or tx.get("memo_type") != "none"):
                    txs_memo.append(tx)
            if registros[-1].get("created_at", "") < inicio:
                break
            url = datos.get(
                "_links", {}).get("next", {}).get("href", "")
            if not url:
                break
            if DEBUG:
                print(f"[DEBUG] Stellar pág. {pagina + 1} "
                f"- {len(txs_memo)} txs acumuladas")

    if DEBUG:
        print(f"[DEBUG] Stellar: {len(txs_memo)} txs con memo")
    return txs_memo

def hedera_extraer(inicio: str,
                   max_paginas: int) -> list[dict]:
    """
    Pagina el Mirror Node y recupera txs con memo.

    Args:
        inicio: fecha mínima (ISO) a incluir.
        max_paginas: tope de páginas a recorrer.

    Returns:
        Lista de transacciones Hedera con memo_base64.
    """
    ruta = (f"/api/v1/transactions?limit={PAGINA_HEDERA}"
            f"&order=desc")
    inicio_epoch = datetime.fromisoformat(inicio).replace(
        tzinfo=timezone.utc).timestamp()
    txs_memo: list[dict] = []
    with httpx.Client(timeout=TIMEOUT) as cliente:
        for pagina in range(max_paginas):
            try:
                r = cliente.get(HEDERA_MIRROR + ruta)
                r.raise_for_status()
                datos = r.json()
            except (httpx.HTTPError, ValueError) as e:
                if DEBUG:
                    print(f"[DEBUG] error Hedera: {e}")
                break
            registros = datos.get("transactions", [])
            if not registros:
                break
            for tx in registros:
                if not FILTRO_MEMO or tx.get("memo_base64"):
                    txs_memo.append(tx)
            ultimo = registros[-1].get(
                "consensus_timestamp", "0")
            if float(ultimo) < inicio_epoch:
                break
            ruta = datos.get("links", {}).get("next", "")
            if not ruta:
                break
            if DEBUG:
                print(f"[DEBUG] Hedera pág. {pagina + 1} "
                      f"- {len(txs_memo)} txs acumuladas")
    if DEBUG:
        print(f"[DEBUG] Hedera: {len(txs_memo)} txs con memo")
    return txs_memo

def algorand_extraer(inicio: str,
                     max_paginas: int) -> list[dict]:
    """
    Pagina el Indexer de Algorand y recupera txs con note.

    Args:
        inicio: fecha mínima (ISO) a incluir (after-time).
        max_paginas: tope de páginas a recorrer.

    Returns:
        Lista de transacciones Algorand con campo note.
    """
    url = (f"{ALGORAND_INDEXER}/v2/transactions"
           f"?after-time={inicio}&limit={PAGINA_ALGORAND}")
    txs_memo: list[dict] = []
    with httpx.Client(timeout=TIMEOUT) as cliente:
        for pagina in range(max_paginas):
            try:
                r = cliente.get(url)
                r.raise_for_status()
                datos = r.json()
            except (httpx.HTTPError, ValueError) as e:
                if DEBUG:
                    print(f"[DEBUG] error Algorand: {e}")
                break
            registros = datos.get("transactions", [])
            if not registros:
                break
            for tx in registros:
                if not FILTRO_MEMO or tx.get("note"):
                    txs_memo.append(tx)
            token = datos.get("next-token", "")
            if not token:
                break
            url = (f"{ALGORAND_INDEXER}/v2/transactions"
                   f"?after-time={inicio}"
                   f"&limit={PAGINA_ALGORAND}&next={token}")
            if DEBUG:
                print(f"[DEBUG] Algorand pág. {pagina + 1} "
                      f"- {len(txs_memo)} txs acumuladas")
    if DEBUG:
        print(f"[DEBUG] Algorand: {len(txs_memo)} txs con note")
    return txs_memo

def fred_serie(series_id: str, inicio: str,
               fin: str) -> list[dict]:
    """
    Descarga las observaciones de una serie de FRED.

    Args:
        series_id: identificador de la serie (p. ej. 'DFF').
        inicio: fecha inicial (ISO).
        fin: fecha final (ISO).

    Returns:
        Lista de observaciones (fecha/valor), o [] si falla.
    """
    if not FRED_API_KEY:
        if DEBUG:
            print("[DEBUG] falta FRED_API_KEY, omito FRED")
        return []
    params = {
        "series_id": series_id,
        "observation_start": inicio,
        "observation_end": fin,
        "api_key": FRED_API_KEY,
        "file_type": "json",}
    try:
        r = requests.get(FRED_API, params=params,
                         timeout=TIMEOUT)
        r.raise_for_status()
        return r.json().get("observations", [])
    except (requests.RequestException, ValueError) as e:
        if DEBUG:
            print(f"[DEBUG] error FRED {series_id}: {e}")
        return []


def fred_extraer(inicio: str,
                 fin: str) -> dict[str, list[dict]]:
    """
    Descarga todas las series definidas en FRED_SERIES.

    Args:
        inicio: fecha inicial (ISO).
        fin: fecha final (ISO).

    Returns:
        Diccionario {series_id: observaciones}.
    """
    resultado: dict[str, list[dict]] = {}
    for series_id in FRED_SERIES:
        if DEBUG:
            print(f"[DEBUG] descargando FRED {series_id}...")
        obs = fred_serie(series_id, inicio, fin)
        resultado[series_id] = obs
        if DEBUG:
            print(f"[DEBUG] FRED {series_id}: {len(obs)} obs")
    return resultado

